def _write_23andme(tmp_path: Path, genotypes: dict[str, tuple[str, int, str]]) -> Path:
    """Write a synthetic 23andMe raw file. genotypes = {rsid: (chrom, pos, gt)}."""
    path = tmp_path / "genome.txt"
    lines = [
        "# This data file generated by 23andMe at: synthetic-test-fixture",
        "# rsid\tchromosome\tposition\tgenotype",
    ]
    for rsid, (chrom, pos, gt) in genotypes.items():
        lines.append(f"{rsid}\t{chrom}\t{pos}\t{gt}")
    path.write_text("\n".join(lines) + "\n")
    return path


class TestParser:
    def test_parse_23andme_basic(self, tmp_path):
        p = _write_23andme(tmp_path, {
            "rs4477212": ("1", 82154, "AA"),
            "rs3094315": ("1", 752566, "AG"),
            "i5000001": ("1", 900000, "CC"),
        })
        calls = parse_23andme(p)
        assert len(calls) == 3
        assert calls["rs4477212"].genotype == "AA"
        assert calls["rs3094315"].chromosome == "1"
        assert calls["rs3094315"].position == 752566

    def test_parser_handles_no_calls(self, tmp_path):
        p = _write_23andme(tmp_path, {
            "rs1": ("1", 100, "--"),
            "rs2": ("1", 200, "AA"),
        })
        calls = parse_23andme(p)
        assert calls["rs1"].is_no_call
        assert not calls["rs2"].is_no_call

    def test_parser_ignores_malformed_lines(self, tmp_path):
        path = tmp_path / "genome.txt"

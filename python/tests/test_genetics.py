class TestGeneticEffectRule:
    def test_rule_matches_only_on_phenotype(self):
        gp_um = GeneticProfile(phenotypes={"CYP2D6": "ultrarapid_metabolizer"})
        gp_nm = GeneticProfile(phenotypes={"CYP2D6": "normal_metabolizer"})
        rule = GeneticEffectRule(
            gene="CYP2D6",
            phenotype="ultrarapid_metabolizer",
            multiplier=0.3,
        )
        assert rule.matches(gp_um)
        assert not rule.matches(gp_nm)
        assert not rule.matches(None)

    def test_catalog_applies_rule(self):
        """Trazodone's CYP2D6 UM rule should shrink its profile-effect multiplier."""
        from optiqal.catalog import CATALOG
        from optiqal.profile import Profile

        base_profile = Profile(
            age=39, sex="male", bmi_category="normal", smoking_status="never",
            has_diabetes=False, has_hypertension=False, activity_level="light",
        )
        trazodone = CATALOG["trazodone_50mg"]

        base_mult = trazodone.profile_effect_multiplier(base_profile)

        um_profile = Profile(
            age=39, sex="male", bmi_category="normal", smoking_status="never",
            has_diabetes=False, has_hypertension=False, activity_level="light",
            genetic_profile=GeneticProfile(
                phenotypes={"CYP2D6": "ultrarapid_metabolizer"},
            ),
        )
        um_mult = trazodone.profile_effect_multiplier(um_profile)
        # With UM rule (0.3x), multiplier should be strictly smaller.
        assert um_mult == pytest.approx(base_mult * 0.3, rel=1e-6)

    def test_catalog_no_rule_no_change(self):
        """Items without genetic rules shouldn't change with genetic_profile."""
        from optiqal.catalog import CATALOG
        from optiqal.profile import Profile

        # finasteride has no genetic rules
        fin = CATALOG["finasteride_1.25mg"]
        p_no = Profile(
            age=39, sex="male", bmi_category="normal", smoking_status="never",
            has_diabetes=False, has_hypertension=False, activity_level="light",
        )
        p_with_pgx = Profile(
            age=39, sex="male", bmi_category="normal", smoking_status="never",
            has_diabetes=False, has_hypertension=False, activity_level="light",
            genetic_profile=GeneticProfile(
                phenotypes={"CYP2D6": "poor_metabolizer"},
            ),
        )
        assert fin.profile_effect_multiplier(p_no) == fin.profile_effect_multiplier(
            p_with_pgx,
        )


